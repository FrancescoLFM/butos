"""
Generates src/drivers/keymaps.h from the layouts in this directory:
    python3 keyboard_gen.py *.json > ../../src/drivers/keymaps.h
Each <name>.json maps scancodes (set 1) to characters for the standard,
shift and altgr tables; the layout is selected by <name>.
"""
import json
import os
import sys

TABLES = ("standard", "shift", "altgr")


def keyboard_to_list(table: dict) -> list:
    keys = [0] * 256

    for scancode, char in table.items():
        keys[int(scancode)] = char

    return keys


def c_char(key) -> str:
    if key == 0:
        return "0"
    if key == "'":
        return "'\\''"
    if key == "\\":
        return "'\\\\'"
    if key == "\b":
        return "'\\b'"
    if key == "\t":
        return "'\\t'"
    if key == "\n":
        return "'\\n'"
    if len(key) != 1 or not key.isascii():
        raise ValueError(f"{key!r} is not an ASCII character")
    return repr(key)


def c_array(name: str, keys: list) -> str:
    lines = []
    for i in range(0, len(keys), 16):
        lines.append("    " + ", ".join(c_char(k) for k in keys[i:i + 16]) + ",")
    return f"static const uint8_t {name}[256] = {{\n" + "\n".join(lines) + "\n};\n"


def main(paths: list) -> None:
    layouts = []

    print("/* Generated by scripts/keyboard/keyboard_gen.py, don't edit */")
    print("#ifndef DRIVERS_KEYMAPS_H")
    print("#define DRIVERS_KEYMAPS_H\n")
    print("#include <include/def.h>\n")
    for path in sorted(paths):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, "r") as infile:
            keyboard = json.load(infile)
        for table in TABLES:
            print(c_array(f"{name.upper()}_{table.upper()}_KEYS", keyboard_to_list(keyboard[table])))
        layouts.append(name)

    print("struct keymap {")
    print("    const char *name;")
    print("    const uint8_t *std_table;")
    print("    const uint8_t *shift_table;")
    print("    const uint8_t *altgr_table;")
    print("};\n")
    print("static const struct keymap keymaps[] = {")
    for name in layouts:
        tables = ", ".join(f"{name.upper()}_{t.upper()}_KEYS" for t in TABLES)
        print(f'    {{"{name}", {tables}}},')
    print("};\n")
    print("#endif")


if __name__ == "__main__":
    main(sys.argv[1:])
